#!/usr/bin/env python3
"""Generate the example sections of the book from examples/index.json.

    python3 scripts/gen_examples_page.py

Writes (never edit these by hand):
  src/generated/<page>.md        the examples of one command page, included by it
  src/reference/examples.md      the catalogue of every example

An example belongs to the page of its directory (examples/order.list/... ->
order_list). Directory `general` goes to the catalogue only.
"""

import json
import pathlib
import shlex
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATED = ROOT / "src" / "generated"
HEADER = "<!-- Generated by scripts/gen_examples_page.py from examples/index.json. Do not edit. -->\n\n"
STATUS_ORDER = {"ok": 0, "uncertain": 1, "error": 2}


def page_of(entry):
    return entry["id"].split("/")[0].replace(".", "_").replace("-", "_")


def body(entry):
    return json.loads((ROOT / "examples" / entry["file"]).read_text())


def block(entry, include_prefix):
    envelope = body(entry)
    code = (envelope.get("error") or {}).get("code")
    status = envelope["status"] + (f" · `{code}`" if code else "")
    source = entry["source"]["kind"]
    lines = [
        f"### {entry['title']}",
        "",
        f"_`{entry['id']}` · status {status} · exit {entry['exit_code']} · {source}_",
        "",
        "```sh",
        shlex.join(entry["argv"]),
        "```",
        "",
    ]
    if entry["id"] == "schema/discovery":
        lines += ["The document is about 110 KB; see `schemas/discovery.json`.", ""]
    else:
        lines += ["```json", f"{{{{#include {include_prefix}{entry['file']}}}}}", "```", ""]
    return "\n".join(lines)


def main():
    index = json.loads((ROOT / "examples" / "index.json").read_text())
    entries = index["examples"]
    by_page = defaultdict(list)
    for entry in entries:
        by_page[page_of(entry)].append(entry)

    GENERATED.mkdir(parents=True, exist_ok=True)
    for old in GENERATED.glob("*.md"):
        old.unlink()
    for page, items in by_page.items():
        if page == "general":
            continue
        items.sort(key=lambda e: (STATUS_ORDER[body(e)["status"]], e["exit_code"], e["id"]))
        text = HEADER + "\n".join(block(e, "../../examples/") for e in items)
        (GENERATED / f"{page}.md").write_text(text)

    rows = ["| Example | Command | Status | Code | Exit | Source |", "| --- | --- | --- | --- | --- | --- |"]
    for entry in sorted(entries, key=lambda e: e["id"]):
        envelope = body(entry)
        code = (envelope.get("error") or {}).get("code") or ""
        rows.append(
            f"| `{entry['id']}` — {entry['title']} | `{entry['command']}` | {envelope['status']} | "
            f"{'`' + code + '`' if code else ''} | {entry['exit_code']} | {entry['source']['kind']} |"
        )
    counts = defaultdict(int)
    for entry in entries:
        counts[entry["source"]["kind"]] += 1
    catalogue = HEADER + "\n".join([
        "# Example catalogue",
        "",
        f"{len(entries)} examples: {counts['fixture']} fixtures from the CLI's test suite, "
        f"{counts['captured']} captured from the binary, {counts['authored']} authored for this book. "
        "Every one validates against the generated schema of its command "
        "(`scripts/validate_examples.py`).",
        "",
        "Files are in `examples/`, one envelope per file, exactly as printed on stdout. "
        "`examples/index.json` adds the command line, exit code, title and source of each.",
        "",
        "- **fixture**: a contract case of the CLI repository (`specs/*/contracts/examples.json`), "
        "reproduced by its tests. Synthetic values.",
        "- **captured**: real output of mostro-cli 0.16.3, run offline.",
        "- **authored**: written for this book from the contract and validated against the schema; "
        "synthetic values.",
        "",
        "## By command",
        "",
        *rows,
        "",
        "## General",
        "",
        *[block(e, "../../examples/") for e in sorted(by_page.get("general", []), key=lambda e: e["id"])],
    ])
    (ROOT / "src" / "reference" / "examples.md").parent.mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "reference" / "examples.md").write_text(catalogue)
    print(f"wrote {len(by_page) - ('general' in by_page)} generated pages and the catalogue")


if __name__ == "__main__":
    main()
